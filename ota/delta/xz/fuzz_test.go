// FuzzDecode is the xz data of an update payload's operation or patch:
// decoding ends in exactly size bytes or an error.
func FuzzDecode(f *testing.F) {
	for i, s := range streams {
		b, _ := hex.DecodeString(s)
		f.Add(b, int32([]int{106, 106, 106, 106, 300}[i]))
	}
	f.Fuzz(func(t *testing.T, in []byte, size int32) {
		if size > 1<<20 {
			return
		}
		out, err := Decode(in, int(size))
		if err == nil && len(out) != int(size) {
			t.Fatalf("%d bytes, %d asked", len(out), size)
		}
	})
}
