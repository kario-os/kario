#!/usr/bin/env python3
"""Write the bitbake crate list for a Cargo.lock, in the format of oe-core's
cargo-update-recipe-crates class: every crate is fetched (and checksummed) by
bitbake, so the Rust build itself runs offline with --frozen.

Usage: cratesinc.py path/to/Cargo.lock > recipe-crates.inc
"""
import sys
import tomllib

lock = tomllib.load(open(sys.argv[1], "rb"))
crates = [p for p in lock["package"] if "crates.io" in p.get("source", "")]
print(f"# Generated by fw/tools/cratesinc.py from {sys.argv[1]} ({len(crates)} crates)\n")
print('SRC_URI += " \\')
for c in crates:
    print(f"    crate://crates.io/{c['name']}/{c['version']} \\")
print('"\n')
for c in crates:
    print(f'SRC_URI[{c["name"]}-{c["version"]}.sha256sum] = "{c["checksum"]}"')
