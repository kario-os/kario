#!/usr/bin/env python3
"""Write the bitbake Go module lists for phone-fw, in the format of oe-core's
go-mod-update-modules class: every module the build needs is fetched and
checksummed by bitbake (gomod://), so the Go build runs offline from the
module cache and vendor/ never enters a build.

  <recipe dir>/<bpn>-go-mods.inc   SRC_URI += "gomod://<module>;version=...;sha256sum=..."
  <recipe dir>/<bpn>-licenses.inc  LICENSE += "& ..." and LIC_FILES_CHKSUM of each module's licence

The modules are what `go list -deps` needs for the recipe's packages on the
target (linux/arm64) and for phone-imedict, which runs on the build host
(linux/amd64), plus the go.mod alone of the rest of the module graph. They are downloaded from the module proxy bitbake uses, so the
checksums are those of the files it will fetch; this needs the network.

The first line of the module list records a digest of go.mod and go.sum;
--check compares it with the tree's (offline, part of `make test`), so the
lists cannot fall behind the module files unnoticed.

Usage: gomodinc.py <recipe dir> <bpn> <package>...
       gomodinc.py --check <recipe dir> <bpn>
"""
import hashlib
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROXY = "https://proxy.golang.org"
PLATFORMS = [("linux", "arm64"), ("linux", "amd64")]
NOTICE = "# Generated by tools/gomodinc.py from go.mod and go.sum; do not edit.\n"


def digest():
    h = hashlib.sha256()
    for f in ("go.mod", "go.sum"):
        with open(os.path.join(ROOT, f), "rb") as fh:
            h.update(fh.read())
    return h.hexdigest()


def check(recipe, bpn):
    path = os.path.join(recipe, f"{bpn}-go-mods.inc")
    with open(path) as fh:
        head = fh.read(400)
    m = re.search(r"# go\.mod \+ go\.sum: ([0-9a-f]{64})", head)
    if not m or m.group(1) != digest():
        sys.exit(f"gomodinc: {path} is not from this go.mod and go.sum; run make gomods")


def license_check():
    spec = importlib.util.spec_from_file_location("license_check", os.path.join(ROOT, "scripts", "license-check.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def unescape(path):
    """The module cache escapes capitals as !x."""
    return re.sub(r"!([a-z])", lambda m: m.group(1).upper(), path)


def fold(uri):
    """Shorter module paths sort before longer ones."""
    return uri.replace(";", " ").replace("/", "!")


def go_list(cache, pkgs):
    """go list on a copy of go.mod and go.sum (-modfile), so the tree's
    stay as they are whatever the go command would add."""
    work = os.path.join(cache, "modfile")
    os.makedirs(work)
    for f in ("go.mod", "go.sum"):
        shutil.copy(os.path.join(ROOT, f), work)
    out = []
    for goos, goarch in PLATFORMS:
        env = dict(os.environ, GOMODCACHE=cache, GOFLAGS="-mod=mod -modfile=" + os.path.join(work, "go.mod"), GOPROXY=PROXY,
                   GOWORK="off", GOOS=goos, GOARCH=goarch, CGO_ENABLED="0")
        raw = subprocess.check_output(["go", "list", "-deps", "-json=Dir,ImportPath,Module", *pkgs], cwd=ROOT, env=env, text=True)
        out += json.loads("[" + raw.replace("}\n{", "},\n{") + "]")
    # The build also loads the go.mod of every module in the module graph,
    # those that only other platforms or tests use included.
    subprocess.check_output(["go", "list", "-m", "all"], cwd=ROOT, env=env, text=True)
    return out


def sha256(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def md5(path):
    with open(path, "rb") as fh:
        return hashlib.md5(fh.read()).hexdigest()


def sources(cache):
    uris = []
    dl = os.path.join(cache, "cache", "download")
    for dirpath, _, files in os.walk(dl):
        path, base = os.path.split(os.path.relpath(dirpath, dl))
        if base != "@v":
            continue
        path = unescape(path)
        zips = {f[:-4] for f in files if f.endswith(".zip")}
        for ver in sorted(zips):
            uris.append(f"gomod://{path};version={ver};sha256sum={sha256(os.path.join(dirpath, ver + '.zip'))}")
        for f in sorted(files):
            if f.endswith(".mod") and f[:-4] not in zips:
                uris.append(f"gomod://{path};version={f[:-4]};mod=1;sha256sum={sha256(os.path.join(dirpath, f))}")
    return sorted(uris, key=fold)


def licenses(cache, pkgs, lc):
    """One licence file per module a package of the build comes from: the
    package's own, else the nearest one up to the module's root."""
    found = {}
    names = set()
    for p in pkgs:
        mod = p.get("Module") or {}
        mdir, pdir = mod.get("Dir", ""), p.get("Dir", "")
        if not mdir.startswith(cache) or mod.get("Path") in found:
            continue
        d = pdir
        hit = None
        while hit is None and d.startswith(mdir):
            for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
                if lc.LICENSE_FILES.match(f):
                    hit = os.path.join(d, f)
                    break
            if d == mdir:
                break
            d = os.path.dirname(d)
        if hit:
            with open(hit, errors="replace") as fh:
                name = lc.classify(fh.read())
        elif mod["Path"] in lc.REVIEWED:
            name, where = lc.REVIEWED[mod["Path"]]
            hit = os.path.join(mdir, where.split(",")[0])
        else:
            sys.exit(f"gomodinc: no licence file for {mod['Path']}")
        if name == "unknown":
            sys.exit(f"gomodinc: unrecognised licence {os.path.relpath(hit, cache)}")
        names.add(name)
        found[mod["Path"]] = f"file://pkg/mod/{os.path.relpath(hit, cache)};md5={md5(hit)};spdx={urllib.parse.quote_plus(name)}"
    return sorted(names), sorted(found.values(), key=fold)


def main():
    if len(sys.argv) == 4 and sys.argv[1] == "--check":
        check(sys.argv[2], sys.argv[3])
        return
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    recipe, bpn, pkgs = sys.argv[1], sys.argv[2], sys.argv[3:]
    lc = license_check()
    cache = tempfile.mkdtemp(prefix="gomodinc-")
    try:
        listed = go_list(cache, pkgs)
        uris = sources(cache)
        names, files = licenses(cache, listed, lc)
    finally:
        subprocess.run(["go", "clean", "-modcache"], cwd=ROOT, env=dict(os.environ, GOMODCACHE=cache), check=False)
        shutil.rmtree(cache, ignore_errors=True)
    with open(os.path.join(recipe, f"{bpn}-go-mods.inc"), "w") as fh:
        fh.write(NOTICE + f"# go.mod + go.sum: {digest()}\n\n")
        fh.write('SRC_URI += "\\\n' + "".join(f"    {u} \\\n" for u in uris) + '"\n')
    with open(os.path.join(recipe, f"{bpn}-licenses.inc"), "w") as fh:
        fh.write(NOTICE + f'\nLICENSE += "& {" & ".join(names)}"\n\n')
        fh.write('LIC_FILES_CHKSUM += "\\\n' + "".join(f"    {f} \\\n" for f in files) + '"\n')
    print(f"gomodinc: {len(uris)} module files, {len(files)} licences ({', '.join(names)})")


if __name__ == "__main__":
    main()
