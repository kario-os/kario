#!/usr/bin/env python3
"""Write the bitbake Go module lists for phone-fw, in the format of oe-core's
go-mod-update-modules class: every module the build needs is fetched and
checksummed by bitbake (gomod://), so the Go build runs offline from the
module cache and vendor/ never enters a build.

  <recipe dir>/<bpn>-go-mods.inc   SRC_URI += "gomod://<module>;version=...;sha256sum=..."
  <recipe dir>/<bpn>-licenses.inc  LICENSE += "& ..." and LIC_FILES_CHKSUM of each module's licence

The modules are what `go list -deps` needs for the recipe's packages on the
target (linux/arm64) and for phone-imedict, which runs on the build host
(linux/amd64), plus the go.mod alone of the rest of the module graph. They are downloaded from the module proxy bitbake uses, so the
checksums are those of the files it will fetch; this needs the network, and
a Go (GO, else go on PATH) at least as new as go.mod's go line: the lists are
written with that toolchain alone (GOTOOLCHAIN=local), never with one the go
command would download, which would enter the lists as a module.

The module list's header records a digest of go.mod's directives
(without comments, // indirect and the toolchain and godebug lines, in any
order: what go mod tidy rearranges does not change the modules) and of
go.sum; --check compares it with the tree's (offline, part of `make test`),
so the lists cannot fall behind the module files unnoticed. --ensure writes
the lists again when they have (make yocto-src). --rev takes go.mod and
go.sum from a commit (SRC=git builds one); --ensure then writes the lists
only if the commit's are this tree's.

Usage: gomodinc.py <recipe dir> <bpn> <package>...
       gomodinc.py --check [--rev REV] <recipe dir> <bpn>
       gomodinc.py --ensure [--rev REV] <recipe dir> <bpn> <package>...
"""
import argparse
import hashlib
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROXY = "https://proxy.golang.org"
PLATFORMS = [("linux", "arm64"), ("linux", "amd64")]
NOTICE = "# Generated by tools/gomodinc.py from go.mod and go.sum; do not edit.\n"
# The go command's bookkeeping, which does not change the module graph.
UNLISTED = {"toolchain", "godebug"}


def go_command():
    return os.environ.get("GO") or "go"


def module_files(rev=None):
    """go.mod and go.sum of the tree, or of commit rev."""
    if rev is None:
        out = []
        for f in ("go.mod", "go.sum"):
            with open(os.path.join(ROOT, f), "rb") as fh:
                out.append(fh.read())
        return out
    try:
        return [subprocess.run(["git", "-C", ROOT, "show", f"{rev}:{f}"], capture_output=True, check=True).stdout
                for f in ("go.mod", "go.sum")]
    except subprocess.CalledProcessError as e:
        sys.exit(f"gomodinc: no go.mod and go.sum at {rev}: {e.stderr.decode(errors='replace').strip()}")


def strip_comment(line):
    quote = None
    for i, c in enumerate(line):
        if quote:
            if c == quote:
                quote = None
        elif c in "\"`":
            quote = c
        elif line.startswith("//", i):
            return line[:i]
    return line


def directives(gomod):
    """go.mod's directives one per line ("require <path> <version>"), sorted."""
    out, block = [], None
    for raw in gomod.decode().splitlines():
        words = strip_comment(raw).split()
        if not words:
            continue
        if block:
            if words == [")"]:
                block = None
            else:
                out.append(" ".join([block] + words))
        elif words[-1] == "(":
            block = " ".join(words[:-1])
        else:
            out.append(" ".join(words))
    return sorted(d for d in out if d.split()[0] not in UNLISTED)


def digest(rev=None):
    gomod, gosum = module_files(rev)
    h = hashlib.sha256()
    h.update("\n".join(directives(gomod)).encode() + b"\n\0")
    h.update(gosum)
    return h.hexdigest()


def recorded(recipe, bpn):
    path = os.path.join(recipe, f"{bpn}-go-mods.inc")
    try:
        with open(path) as fh:
            head = fh.read(400)
    except FileNotFoundError:
        return None
    m = re.search(r"# go\.mod \+ go\.sum: ([0-9a-f]{64})", head)
    return m and m.group(1)


def check(recipe, bpn, rev=None):
    if recorded(recipe, bpn) != digest(rev):
        where = f"{rev}'s go.mod and go.sum" if rev else "this go.mod and go.sum"
        sys.exit(f"gomodinc: {os.path.join(recipe, f'{bpn}-go-mods.inc')} is not from {where}; run make gomods")


def ensure(recipe, bpn, pkgs, rev=None):
    want = digest(rev)
    if recorded(recipe, bpn) == want:
        return
    path = os.path.join(recipe, f"{bpn}-go-mods.inc")
    if rev and want != digest():
        sys.exit(f"gomodinc: {path} is not from {rev}'s go.mod and go.sum, which SRC=git builds, and they are not "
                 f"this tree's, which it would be written from: check out {rev} (or build this tree, SRC=tarball)")
    print(f"gomodinc: {path} is not from this go.mod and go.sum: writing it again (make gomods)", file=sys.stderr)
    generate(recipe, bpn, pkgs)


def version(text):
    """The numbers of a Go version: (1, 25, 0) of go1.25.0, (1, 26) of go1.26rc1."""
    m = re.search(r"(\d+(?:\.\d+)*)", text)
    return tuple(int(n) for n in m.group(1).split(".")) if m else ()


def need_go(gomod):
    """Stop unless the go command is as new as go.mod's go line."""
    m = re.search(r"^go\s+(\S+)", gomod.decode(), re.M)
    if not m:
        return
    want, go = m.group(1), go_command()
    try:
        have = subprocess.run([go, "env", "GOVERSION"], cwd=tempfile.gettempdir(), capture_output=True, text=True,
                              env=dict(os.environ, GOTOOLCHAIN="local"), check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as e:
        sys.exit(f"gomodinc: no working {go} ({e}): go.mod needs Go {want} or newer (https://go.dev/dl/; GO= names it)")
    if version(have) < version(want):
        sys.exit(f"gomodinc: go.mod needs Go {want} or newer; {shutil.which(go) or go} is {have}. Install Go {want} "
                 "or newer (https://go.dev/dl/) first on PATH, or name it with GO=: the lists are written with "
                 "the local toolchain only (GOTOOLCHAIN=local)")


def license_check():
    spec = importlib.util.spec_from_file_location("license_check", os.path.join(ROOT, "scripts", "license-check.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def unescape(path):
    """The module cache escapes capitals as !x."""
    return re.sub(r"!([a-z])", lambda m: m.group(1).upper(), path)


def fold(uri):
    """Shorter module paths sort before longer ones."""
    return uri.replace(";", " ").replace("/", "!")


def go_list(cache, pkgs):
    """go list on a copy of go.mod and go.sum (-modfile), so the tree's
    stay as they are whatever the go command would add."""
    work = os.path.join(cache, "modfile")
    os.makedirs(work)
    for f in ("go.mod", "go.sum"):
        shutil.copy(os.path.join(ROOT, f), work)
    go, out = go_command(), []
    for goos, goarch in PLATFORMS:
        env = dict(os.environ, GOMODCACHE=cache, GOFLAGS="-mod=mod -modfile=" + os.path.join(work, "go.mod"), GOPROXY=PROXY,
                   GOWORK="off", GOTOOLCHAIN="local", GOOS=goos, GOARCH=goarch, CGO_ENABLED="0")
        raw = subprocess.check_output([go, "list", "-deps", "-json=Dir,ImportPath,Module", *pkgs], cwd=ROOT, env=env, text=True)
        out += json.loads("[" + raw.replace("}\n{", "},\n{") + "]")
    # The build also loads the go.mod of every module in the module graph,
    # those that only other platforms or tests use included.
    subprocess.check_output([go, "list", "-m", "all"], cwd=ROOT, env=env, text=True)
    return out


def sha256(path):
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def md5(path):
    with open(path, "rb") as fh:
        return hashlib.md5(fh.read()).hexdigest()


def sources(cache):
    uris = []
    dl = os.path.join(cache, "cache", "download")
    for dirpath, _, files in os.walk(dl):
        path, base = os.path.split(os.path.relpath(dirpath, dl))
        if base != "@v":
            continue
        path = unescape(path)
        zips = {f[:-4] for f in files if f.endswith(".zip")}
        for ver in sorted(zips):
            uris.append(f"gomod://{path};version={ver};sha256sum={sha256(os.path.join(dirpath, ver + '.zip'))}")
        for f in sorted(files):
            if f.endswith(".mod") and f[:-4] not in zips:
                uris.append(f"gomod://{path};version={f[:-4]};mod=1;sha256sum={sha256(os.path.join(dirpath, f))}")
    return sorted(uris, key=fold)


def licenses(cache, pkgs, lc):
    """One licence file per module a package of the build comes from: the
    package's own, else the nearest one up to the module's root."""
    found = {}
    names = set()
    for p in pkgs:
        mod = p.get("Module") or {}
        mdir, pdir = mod.get("Dir", ""), p.get("Dir", "")
        if not mdir.startswith(cache) or mod.get("Path") in found:
            continue
        d = pdir
        hit = None
        while hit is None and d.startswith(mdir):
            for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
                if lc.LICENSE_FILES.match(f):
                    hit = os.path.join(d, f)
                    break
            if d == mdir:
                break
            d = os.path.dirname(d)
        if hit:
            with open(hit, errors="replace") as fh:
                name = lc.classify(fh.read())
        elif mod["Path"] in lc.REVIEWED:
            name, where = lc.REVIEWED[mod["Path"]]
            hit = os.path.join(mdir, where.split(",")[0])
        else:
            sys.exit(f"gomodinc: no licence file for {mod['Path']}")
        if name == "unknown":
            sys.exit(f"gomodinc: unrecognised licence {os.path.relpath(hit, cache)}")
        names.add(name)
        found[mod["Path"]] = f"file://pkg/mod/{os.path.relpath(hit, cache)};md5={md5(hit)};spdx={urllib.parse.quote_plus(name)}"
    return sorted(names), sorted(found.values(), key=fold)


def generate(recipe, bpn, pkgs):
    need_go(module_files()[0])
    lc = license_check()
    cache = tempfile.mkdtemp(prefix="gomodinc-")
    try:
        listed = go_list(cache, pkgs)
        uris = sources(cache)
        names, files = licenses(cache, listed, lc)
    except subprocess.CalledProcessError as e:
        sys.exit(f"gomodinc: `{' '.join(e.cmd[:3])}` failed (above): the lists need every module from {PROXY}, "
                 "the proxy bitbake fetches from (the network, or https_proxy)")
    finally:
        subprocess.run([go_command(), "clean", "-modcache"], cwd=ROOT, env=dict(os.environ, GOMODCACHE=cache, GOTOOLCHAIN="local"),
                       check=False)
        shutil.rmtree(cache, ignore_errors=True)
    with open(os.path.join(recipe, f"{bpn}-go-mods.inc"), "w") as fh:
        fh.write(NOTICE + f"# go.mod + go.sum: {digest()}\n\n")
        fh.write('SRC_URI += "\\\n' + "".join(f"    {u} \\\n" for u in uris) + '"\n')
    with open(os.path.join(recipe, f"{bpn}-licenses.inc"), "w") as fh:
        fh.write(NOTICE + f'\nLICENSE += "& {" & ".join(names)}"\n\n')
        fh.write('LIC_FILES_CHKSUM += "\\\n' + "".join(f"    {f} \\\n" for f in files) + '"\n')
    print(f"gomodinc: {len(uris)} module files, {len(files)} licences ({', '.join(names)})")


def main():
    ap = argparse.ArgumentParser(usage=__doc__.split("Usage: ", 1)[1])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--ensure", action="store_true")
    ap.add_argument("--rev")
    ap.add_argument("recipe")
    ap.add_argument("bpn")
    ap.add_argument("pkgs", nargs="*")
    a = ap.parse_args()
    if a.check:
        check(a.recipe, a.bpn, a.rev)
    elif not a.pkgs or (a.rev and not a.ensure):
        ap.error("the packages are missing" if not a.pkgs else "--rev goes with --check or --ensure")
    elif a.ensure:
        ensure(a.recipe, a.bpn, a.pkgs, a.rev)
    else:
        generate(a.recipe, a.bpn, a.pkgs)


if __name__ == "__main__":
    main()
