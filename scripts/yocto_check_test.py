SUM = "3ad5a18d99f322f635de3c9f31b54836b2995527e01d813e8acb557ea7374aed"


class PinnedSources(unittest.TestCase):
    def test_a_git_repository_at_a_commit(self):
        recipe = f'SRC_URI = "git://gitlab.nura.eco/modem/81voltd.git;protocol=https;branch=main;tag=v${{PV}} \\\n           file://81voltd.service"\nSRCREV = "{REV}"\n'
        self.assertEqual(yc.unpinned_sources(recipe, "1.2.0"), [])
        self.assertEqual(yc.unpinned_sources(recipe.replace(f'SRCREV = "{REV}"\n', ""), "1.2.0"),
                         ["git://gitlab.nura.eco/modem/81voltd.git: no commit in SRCREV"])
        self.assertEqual(yc.unpinned_sources(recipe.replace(REV, "${AUTOREV}")),
                         ["git://gitlab.nura.eco/modem/81voltd.git: no commit in SRCREV (it is ${AUTOREV})"])
        self.assertEqual(len(yc.unpinned_sources(recipe.replace(REV, REV[:12]))), 1)

    def test_named_sources(self):
        recipe = (f'SRC_URI = "git://gitlab.com/sdm845-mainline/linux.git;protocol=https;nobranch=1;tag=${{TAG}};name=machine \\\n'
                  f'           https://example.org/config;name=defconfig;downloadfilename=defconfig"\n'
                  f'SRCREV_machine = "{REV}"\nSRC_URI[defconfig.sha256sum] = "{SUM}"\n')
        self.assertEqual(yc.unpinned_sources(recipe), [])
        self.assertEqual(yc.unpinned_sources(recipe.replace("SRCREV_machine", "SRCREV")),
                         ["git://gitlab.com/sdm845-mainline/linux.git: no commit in SRCREV_machine"])
        self.assertEqual(yc.unpinned_sources(recipe.replace("[defconfig.sha256sum]", "[sha256sum]")),
                         ["https://example.org/config: no SRC_URI[defconfig.sha256sum]"])

    def test_a_download_through_a_variable(self):
        recipe = f'BASE = "https://github.com/x/y/raw/v1"\nSRC_URI = "${{BASE}}/LICENSE"\nSRC_URI[sha256sum] = "{SUM}"\n'
        self.assertEqual(yc.unpinned_sources(recipe), [])
        self.assertEqual(yc.unpinned_sources(recipe.replace(SUM, "")), ["https://github.com/x/y/raw/v1/LICENSE: no SRC_URI[sha256sum]"])
        self.assertEqual(yc.unpinned_sources('SRC_URI:append = " ftp://example.org/a.tar.gz"\n'), ["ftp://example.org/a.tar.gz: no SRC_URI[sha256sum]"])

    def test_what_is_left_out(self):
        self.assertEqual(yc.unpinned_sources('SRC_URI = "${@phone_src(d, \'file://phone-gui-src.tar.gz\')}"\n'
                                             'SRC_URI += "crate://crates.io/ab_glyph/0.2.32 file://a.cfg ${UNKNOWN}/x"\n'
                                             'SRC_URI:append:qemuarm64 = " file://b.cfg"\n'), [])

    def test_the_layer_s_recipes(self):
        layer = os.path.join(HERE, "..", "yocto", "meta-phone")
        for rel, pv in (("recipes-bsp/81voltd/81voltd_1.2.0.bb", "1.2.0"), ("recipes-bsp/q6voiced/q6voiced_0.3.1.bb", "0.3.1"),
                        ("recipes-graphics/fonts-noto-cjk/fonts-noto-cjk_2.004.bb", "2.004")):
            with open(os.path.join(layer, rel), encoding="utf-8") as f:
                self.assertEqual(yc.unpinned_sources(f.read(), pv), [], rel)


class SourceDir(unittest.TestCase):
    SERVICES = "SRC_URI = \"${@'file://%s;subdir=services' % d.getVar('PHONE_SERVICES') if d.getVar('PHONE_SERVICES') else ''}\"\n"

    # phone-services left S at ${UNPACKDIR}/${BP}, and every build with
    # PHONE_SERVICES warned at do_unpack (2026-11-25).
    def test_local_files_without_s(self):
        self.assertIn("local files and no S", yc.source_dir_problem(self.SERVICES))
        self.assertIn("local files and no S", yc.source_dir_problem('SRC_URI = "file://a.conf \\\n           file://b.service"\n'))
        self.assertIsNone(yc.source_dir_problem(self.SERVICES + 'S = "${UNPACKDIR}"\n'))

    def test_where_s_is_found_otherwise(self):
        self.assertIsNone(yc.source_dir_problem('SRC_URI = "file://verity-hook"\n', {"bundle"}))
        self.assertIsNone(yc.source_dir_problem("SRC_URI = \"${@phone_src(d, 'file://phone-fw-src.tar.gz;subdir=${BP}/src')}\"\n"))
        self.assertIsNone(yc.source_dir_problem('SRC_URI = "git://gitlab.nura.eco/nura/q6voiced.git;branch=master file://q6voiced.service"\n'))
        self.assertIsNone(yc.source_dir_problem('BASE = "https://example.org/fonts"\nSRC_URI = "${BASE}/a.ttc file://LICENSE"\n'))
        self.assertIsNone(yc.source_dir_problem('SUMMARY = "The image"\ninherit core-image\n'))

    def test_s_bitbake_refuses(self):
        self.assertIn("stops the build", yc.source_dir_problem('SRC_URI = "file://a"\nS = "${WORKDIR}"\n'))
        self.assertIn("stops the build", yc.source_dir_problem('SRC_URI = "git://x/y.git;branch=main"\nS = "${UNPACKDIR}/git"\n'))

    def test_the_layer_s_recipes(self):
        for root, _, names in os.walk(os.path.join(HERE, "..", "yocto", "meta-phone")):
            for name in names:
                if name.endswith(".bb"):
                    with open(os.path.join(root, name), encoding="utf-8") as f:
                        text = f.read()
                    inherits = set(" ".join(re.findall(r"^inherit\s+(.+)$", text, re.M)).split())
                    self.assertIsNone(yc.source_dir_problem(text, inherits), name)


class PackageKeys(unittest.TestCase):
    # The kas file cleared two packages' dependencies with :forcevariable,
    # and every parse warned "Variable key RDEPENDS:${PN}-misc (perl)
    # replaces original key RDEPENDS:openssl-misc ()" (2026-11-25).
    def test_set_other_than_with_remove(self):
        conf = ('    RDEPENDS:systemd-ukify:forcevariable = ""\n    RDEPENDS:openssl-misc:forcevariable = ""\n'
                '    RRECOMMENDS:foo += "bar"\n    RDEPENDS:glib-2.0-utils:append = " x"\n')
        self.assertEqual(yc.package_key_assignments(conf), ["RDEPENDS:systemd-ukify:forcevariable", "RDEPENDS:openssl-misc:forcevariable",
                                                            "RRECOMMENDS:foo", "RDEPENDS:glib-2.0-utils:append"])

    def test_taken_out_with_remove(self):
        conf = ('    RDEPENDS:openssl-misc:remove = "perl"\n    RRECOMMENDS:systemd-container:remove = "tar"\n'
                '    CODEGEN_PYTHON_RDEPENDS:forcevariable = ""\nMACHINE_ESSENTIAL_EXTRA_RDEPENDS += "x"\n'
                '    RDEPENDS:append:pn-foo = " bar"\n')
        self.assertEqual(yc.package_key_assignments(conf), [])

    def test_the_kas_files(self):
        kas = os.path.join(HERE, "..", "yocto", "kas")
        for name in sorted(os.listdir(kas)):
            if name.endswith(".yml"):
                with open(os.path.join(kas, name), encoding="utf-8") as f:
                    self.assertEqual(yc.package_key_assignments(f.read()), [], name)


