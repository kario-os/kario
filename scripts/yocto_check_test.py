class ModuleKey(unittest.TestCase):
    def test_the_fragments_of_d4856a3(self):
        # The 6T's fragment turned signing on and left the kernel its own key.
        got = yc.module_key_problems({"phone-fajita.cfg": "CONFIG_MODULE_SIG=y\n# CONFIG_MODULE_COMPRESS is not set\n",
                                      "phone-vpn.cfg": "CONFIG_WIREGUARD=y\n"}, "do_install:prepend() {\n}\n")
        self.assertEqual(len(got), 1)
        self.assertIn("phone-fajita.cfg sign modules with the key the kernel generates", got[0])

    def test_the_key_put_in_place(self):
        self.assertEqual(yc.module_key_problems({"phone-lockdown.cfg": 'CONFIG_MODULE_SIG=y\nCONFIG_MODULE_SIG_KEY="certs/kario-modules.pem"\n'}, INC), [])

    def test_the_autogenerated_key_named(self):
        got = yc.module_key_problems({"a.cfg": 'CONFIG_MODULE_SIG=y\nCONFIG_MODULE_SIG_KEY="certs/signing_key.pem"\n'}, INC)
        self.assertEqual(got, ["a.cfg: CONFIG_MODULE_SIG_KEY is certs/signing_key.pem, the key the kernel generates in each build"])

    def test_a_key_nothing_puts_there(self):
        got = yc.module_key_problems({"a.cfg": "CONFIG_MODULE_SIG=y\n", "b.cfg": 'CONFIG_MODULE_SIG_KEY="certs/other.pem"\n'}, INC)
        self.assertEqual(got, ["b.cfg: CONFIG_MODULE_SIG_KEY is certs/other.pem, which phone-kernel.inc does not put in place"])

    def test_no_signing(self):
        self.assertEqual(yc.module_key_problems({"a.cfg": "# CONFIG_MODULE_SIG is not set\n"}, ""), [])


