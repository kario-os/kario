class ShellUnitKillMode(unittest.TestCase):
    SHELL = "[Service]\nExecStart=/usr/bin/phone-shell --services system --gui auto\n"

    # KillMode=process left the panel's renderer running after the Shell on
    # the 6T (2026-11-24), and phone-display could not start again.
    def test_the_shell_s_group_is_killed(self):
        self.assertEqual(yc.shell_unit_kill_mode(self.SHELL + "KillMode=process\n"), "process")
        self.assertEqual(yc.shell_unit_kill_mode(self.SHELL + "KillMode=none\n"), "none")
        self.assertIsNone(yc.shell_unit_kill_mode(self.SHELL + "KillMode=mixed\n"))
        self.assertIsNone(yc.shell_unit_kill_mode(self.SHELL))

    def test_through_a_shell_and_other_units(self):
        self.assertEqual(yc.shell_unit_kill_mode("ExecStart=/bin/sh -c 'exec /usr/bin/phone-shell --script x'\nKillMode=process\n"), "process")
        self.assertIsNone(yc.shell_unit_kill_mode("ExecStart=/usr/bin/phone-audiod --run-dir /run/phone\nKillMode=process\n"))

    def test_the_layer_s_units(self):
        files = os.path.join(HERE, "..", "yocto", "meta-phone", "recipes-phone", "phone-fw", "files")
        for unit in ("phone-display.service", "phone-fdstore-check.service"):
            with open(os.path.join(files, unit), encoding="utf-8") as f:
                self.assertIsNone(yc.shell_unit_kill_mode(f.read()), unit)


